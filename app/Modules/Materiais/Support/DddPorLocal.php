    public static function sugerir(?string $uf, ?float $latitude, ?float $longitude): ?string
    {
        $uf = $uf !== null ? strtoupper($uf) : null;
        $ddds = $uf !== null ? (TelefoneBrasil::DDDS_POR_UF[$uf] ?? null) : null;
        if ($ddds === null) {
            return null;
        }
        if (count($ddds) === 1) {
            return $ddds[0];
        }
        if ($latitude === null || $longitude === null) {
            return null;
        }

        $melhor = null;
        $menor = INF;
        foreach (self::REFERENCIAS as [$ddd, $daUf, $lat, $lng]) {
            if ($daUf !== $uf) {
                continue;
            }
            // Distância aproximada (graus, com a longitude encolhida pela latitude): basta para comparar.
            $d = ($lat - $latitude) ** 2 + (($lng - $longitude) * cos(deg2rad($latitude))) ** 2;
            if ($d < $menor) {
                $menor = $d;
                $melhor = $ddd;
            }
        }

        return $melhor;
    }
